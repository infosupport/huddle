// ── Host pipe op `sbx.kit`: the Huddle CA for a Docker Sandbox ──
// Huddle inspects TLS (it terminates it with its own CA) for a devcontainer, and
// the devcontainer is set up to trust that CA. A Docker Sandbox gets the same
// through an sbx kit (a "mixin": `sbx create --kit <dir>`), which sbx applies to
// the sandbox at create:
//   - the CA in the system trust store (install, as root);
//   - NODE_EXTRA_CA_CERTS / SSL_CERT_FILE / REQUESTS_CA_BUNDLE, like a devcontainer,
//     but all on the system bundle: that keeps sbx's own proxy CA, which sbx's
//     credential proxy needs (a tool trusting only the Huddle CA breaks there);
//   - the CA in the keystore of a JetBrains backend (the JBR does not read the
//     system store), also for a backend Toolbox installs later.
// The op writes the kit to ~/.huddle/sbx/kits/huddle-ca and returns its host path.

import fs from 'fs';
import path from 'path';
import { CONFIG_DIR } from '../config';
import { PipeError, ensurePrivateDir } from './protocol';
import { toHuddlePath } from './fs-list';

export const SBX_KITS_DIR = path.join(CONFIG_DIR, 'sbx', 'kits');
export const KIT_NAME = 'huddle-ca';

const PEM_RE = /^-----BEGIN CERTIFICATE-----\r?\n[A-Za-z0-9+/=\r\n]+-----END CERTIFICATE-----\r?\n?$/;
const MAX_PEM = 16 * 1024;

// In the sandbox, files/home/ is /home/agent/.
const IN_BOX = '/home/agent/.huddle-ca';
const BUNDLE = '/etc/ssl/certs/ca-certificates.crt';

const SPEC = `schemaVersion: "2"
kind: mixin
name: ${KIT_NAME}
description: Trust the Huddle CA, so Huddle can inspect this sandbox's TLS
environment:
  variables:
    NODE_EXTRA_CA_CERTS: ${BUNDLE}
    SSL_CERT_FILE: ${BUNDLE}
    REQUESTS_CA_BUNDLE: ${BUNDLE}
setup:
  install:
    - command: "sh ${IN_BOX}/install.sh"
      user: "0"
  # startup takes the command as argv, install as one string (sbx's schema).
  startup:
    - command: ["sh", "${IN_BOX}/jbr-watch.sh"]
`;

const INSTALL = `#!/bin/sh
# Generated by Huddle. Runs as root when the sandbox is created.
set -e
mkdir -p /usr/local/share/ca-certificates
install -m 0644 ${IN_BOX}/huddle-ca.crt /usr/local/share/ca-certificates/huddle-ca.crt
# sbx's own proxy CA into the same store, so the bundle the variables point at
# trusts both (sbx's credential proxy signs with that one).
if [ -n "\${PROXY_CA_CERT_B64:-}" ]; then
  echo "$PROXY_CA_CERT_B64" | base64 -d > /usr/local/share/ca-certificates/sbx-proxy-ca.crt 2>/dev/null \\
    && chmod 644 /usr/local/share/ca-certificates/sbx-proxy-ca.crt \\
    || rm -f /usr/local/share/ca-certificates/sbx-proxy-ca.crt
fi
update-ca-certificates >/dev/null 2>&1 || true
echo "[huddle] CA installed"
`;

// A JetBrains backend runs on its own JVM (the JBR), which only trusts its own
// keystore. Toolbox installs it under ~/.cache/JetBrains/RemoteDev/dist on the
// first connect, so this keeps watching (in the background) and imports the CA
// into every backend it finds, once.
const JBR_WATCH = `#!/bin/sh
# Generated by Huddle. Runs as the agent user on every sandbox start.
CA=/usr/local/share/ca-certificates/huddle-ca.crt
[ -f "$CA" ] || CA=${IN_BOX}/huddle-ca.crt
import_all() {
  for d in "$HOME"/.cache/JetBrains/RemoteDev/dist/*/; do
    kt="$d/jbr/bin/keytool"; ks="$d/jbr/lib/security/cacerts"
    [ -x "$kt" ] && [ -f "$ks" ] && [ ! -f "$d/.huddle-ca" ] || continue
    "$kt" -delete -alias huddle-ca -keystore "$ks" -storepass changeit >/dev/null 2>&1 || true
    "$kt" -importcert -noprompt -trustcacerts -alias huddle-ca -file "$CA" -keystore "$ks" -storepass changeit >/dev/null 2>&1 \\
      && touch "$d/.huddle-ca"
  done
}
import_all
( while sleep 30; do import_all; done ) >/dev/null 2>&1 </dev/null &
exit 0
`;

/** The `sbx.kit` op: `{ caPem }` → `{ dir }`, the kit's folder as a host path. */
export function sbxKit(args: Record<string, unknown>, root: string = SBX_KITS_DIR, platform: NodeJS.Platform = process.platform): { dir: string } {
  const { caPem } = args;
  if (typeof caPem !== 'string' || caPem.length > MAX_PEM || !PEM_RE.test(caPem)) {
    throw new PipeError('bad_request', 'caPem must be one PEM certificate');
  }
  const dir = path.join(root, KIT_NAME);
  try {
    ensurePrivateDir(root);
    ensurePrivateDir(dir);
    const home = path.join(dir, 'files', 'home', '.huddle-ca');
    fs.mkdirSync(home, { recursive: true, mode: 0o700 });
    // \n only: these are read inside the Linux sandbox, also when written on Windows.
    const write = (file: string, text: string) => fs.writeFileSync(file, text.replace(/\r\n/g, '\n'), { mode: 0o644 });
    write(path.join(dir, 'spec.yaml'), SPEC);
    write(path.join(home, 'huddle-ca.crt'), caPem.endsWith('\n') ? caPem : `${caPem}\n`);
    write(path.join(home, 'install.sh'), INSTALL);
    write(path.join(home, 'jbr-watch.sh'), JBR_WATCH);
  } catch (err) {
    throw new PipeError('internal', `could not write the sbx kit: ${(err as Error).message ?? err}`);
  }
  return { dir: toHuddlePath(dir, platform) };
}
