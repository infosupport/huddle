// ── Host pipe: the agent's serve loop ─────────────────────────────────────────
// Polls the pipe folder for `<id>.in`, claims each by renaming it to
// `<id>.busy` (so it is handled exactly once, even if two agents race), runs it
// without blocking the loop (a 10-minute `sbx create` must not hold up a folder
// listing), writes `<id>.out` atomically and deletes the `.busy`. Every request
// gets a reply, a malformed one included; nothing a request contains can crash
// the loop. See docs/host-pipe.md for the protocol.

import fs from 'fs';
import os from 'os';
import path from 'path';
import { cliVersion } from '../self-update';
import {
  HEARTBEAT_FILE,
  HEARTBEAT_MS,
  Heartbeat,
  MAX_FOLDER_ENTRIES,
  PipeError,
  PipeReply,
  PipeRequest,
  POLL_MS,
  ensurePrivateDir,
  PROTOCOL_VERSION,
  STALE_FILE_MS,
  readHeartbeat,
  writeJsonAtomic,
} from './protocol';
import { fsList, toHuddlePath } from './fs-list';
import { availableTools, toolRun, toolsInfo } from './tools';
import { sbxKit } from './sbx-kit';
import { sbxLinks } from './sbx-links';
import { sshHost, sshKey } from './ssh-hosts';

export interface ServeOptions {
  dir: string;
  /** Lowered in tests; defaults to the contract's values. */
  maxEntries?: number;
  pollMs?: number;
  heartbeatMs?: number;
  log?: (msg: string) => void;
  /** Called when another agent took over the folder; the loop has stopped by then. */
  onReplaced?: () => void;
}

export interface ServeHandle {
  /** Stops polling and the heartbeat, removes host.json (if it is ours) and resolves once in-flight requests have replied. */
  stop(): Promise<void>;
}

// Ids are generated by the gateway (32 hex); anything that does not look like
// an id is not ours and is left alone rather than turned into a reply path.
const REQUEST_RE = /^([A-Za-z0-9_-]{1,128})\.in$/;
const LEFTOVER_RE = /\.(in|busy|out|tmp)$/;

async function dispatch(req: PipeRequest, maxEntries: number): Promise<unknown> {
  const args = req.args ?? {};
  switch (req.op) {
    case 'host.info':
      return {
        platform: process.platform,
        version: cliVersion(),
        home: toHuddlePath(os.homedir()),
        tools: await toolsInfo(),
      };
    case 'fs.list':
      return fsList(args, maxEntries);
    case 'tool.run':
      return toolRun(args);
    case 'sbx.links':
      return sbxLinks(args);
    case 'sbx.kit':
      return sbxKit(args);
    case 'ssh.key':
      return sshKey(args);
    case 'ssh.host':
      return sshHost(args);
    default:
      throw new PipeError('unknown_op', `unknown op '${req.op}'`);
  }
}

function parseRequest(text: string): PipeRequest {
  let req: unknown;
  try {
    req = JSON.parse(text);
  } catch {
    throw new PipeError('bad_request', 'request is not valid JSON');
  }
  if (typeof req !== 'object' || req === null || Array.isArray(req)) throw new PipeError('bad_request', 'request must be a JSON object');
  const r = req as Record<string, unknown>;
  if (r.v !== PROTOCOL_VERSION) throw new PipeError('bad_request', `unsupported protocol version ${JSON.stringify(r.v)} (agent speaks ${PROTOCOL_VERSION})`);
  if (typeof r.op !== 'string' || !r.op) throw new PipeError('bad_request', 'op must be a non-empty string');
  if (r.args !== undefined && (typeof r.args !== 'object' || r.args === null || Array.isArray(r.args))) {
    throw new PipeError('bad_request', 'args must be an object');
  }
  return r as unknown as PipeRequest;
}

/** Deletes request/reply leftovers older than STALE_FILE_MS, skipping ids still in flight. */
export function cleanStale(dir: string, inFlight: Set<string> = new Set(), now: number = Date.now()): string[] {
  const removed: string[] = [];
  let names: string[];
  try {
    names = fs.readdirSync(dir);
  } catch {
    return removed;
  }
  for (const name of names) {
    if (!LEFTOVER_RE.test(name) || inFlight.has(name.split('.')[0])) continue;
    const file = path.join(dir, name);
    try {
      if (now - fs.statSync(file).mtimeMs > STALE_FILE_MS) {
        fs.unlinkSync(file);
        removed.push(name);
      }
    } catch { /* gone already, or not ours to delete */ }
  }
  return removed;
}

export function servePipe(opts: ServeOptions): ServeHandle {
  const { dir } = opts;
  const maxEntries = opts.maxEntries ?? MAX_FOLDER_ENTRIES;
  const log = opts.log ?? (() => {});
  ensurePrivateDir(dir);

  const startedAt = new Date().toISOString();
  const version = cliVersion();
  const inFlight = new Map<string, Promise<void>>();
  let stopped = false;
  let pollTimer: NodeJS.Timeout | undefined;
  let heartbeatTimer: NodeJS.Timeout | undefined;
  let cleanupTimer: NodeJS.Timeout | undefined;

  const removed = cleanStale(dir);
  if (removed.length) log(`removed ${removed.length} stale file(s)`);

  const handle = async (id: string): Promise<void> => {
    const busy = path.join(dir, `${id}.busy`);
    let reply: PipeReply;
    let op = '?';
    try {
      const req = parseRequest(await fs.promises.readFile(busy, 'utf8'));
      op = req.op;
      reply = { ok: true, result: await dispatch(req, maxEntries) };
    } catch (err) {
      reply = err instanceof PipeError
        ? { ok: false, error: { code: err.code, message: err.message } }
        : { ok: false, error: { code: 'internal', message: err instanceof Error ? err.message : String(err) } };
    }
    try {
      writeJsonAtomic(path.join(dir, `${id}.out`), reply);
    } catch (err) {
      log(`${id} ${op}: could not write reply: ${err instanceof Error ? err.message : err}`);
    }
    try { fs.unlinkSync(busy); } catch { /* already gone */ }
    log(`${id} ${op} -> ${reply.ok ? 'ok' : reply.error.code}`);
  };

  const poll = async (): Promise<void> => {
    let names: string[] = [];
    try {
      names = await fs.promises.readdir(dir);
    } catch {
      // The folder went away (e.g. ~/.huddle was removed); recreate and carry on.
      try { ensurePrivateDir(dir); } catch { /* retry next tick */ }
    }
    for (const name of names) {
      const m = REQUEST_RE.exec(name);
      if (!m || stopped) continue;
      const id = m[1];
      // Claiming is the rename: whoever renames first owns the request. A
      // failure means someone else got it (or the gateway gave up on it).
      try {
        fs.renameSync(path.join(dir, name), path.join(dir, `${id}.busy`));
      } catch {
        continue;
      }
      const p = handle(id).finally(() => inFlight.delete(id));
      inFlight.set(id, p);
    }
    if (!stopped) pollTimer = setTimeout(() => void poll(), opts.pollMs ?? POLL_MS);
  };

  const heartbeat = (): void => {
    const file = path.join(dir, HEARTBEAT_FILE);
    // Another agent (a newer CLI started by `huddle init`) took over: step aside
    // rather than fight over host.json every two seconds.
    const current = readHeartbeat(dir);
    if (current && current.pid !== process.pid && current.startedAt > startedAt) {
      log(`replaced by pid ${current.pid}; stopping`);
      void stop().then(() => opts.onReplaced?.());
      return;
    }
    const hb: Heartbeat = {
      v: PROTOCOL_VERSION,
      pid: process.pid,
      version,
      platform: process.platform,
      tools: availableTools(),
      startedAt,
      updatedAt: new Date().toISOString(),
    };
    try {
      writeJsonAtomic(file, hb);
    } catch (err) {
      log(`could not write heartbeat: ${err instanceof Error ? err.message : err}`);
    }
  };

  heartbeatTimer = setInterval(heartbeat, opts.heartbeatMs ?? HEARTBEAT_MS);
  heartbeat();
  // Orphaned replies (the gateway timed out and never collected them) would
  // otherwise pile up for as long as the agent runs.
  cleanupTimer = setInterval(() => cleanStale(dir, new Set(inFlight.keys())), STALE_FILE_MS);
  cleanupTimer.unref();
  void poll();

  async function stop(): Promise<void> {
    if (!stopped) {
      stopped = true;
      clearTimeout(pollTimer);
      clearInterval(heartbeatTimer);
      clearInterval(cleanupTimer);
      const current = readHeartbeat(dir);
      if (current && current.pid === process.pid && current.startedAt === startedAt) {
        try { fs.unlinkSync(path.join(dir, HEARTBEAT_FILE)); } catch { /* already gone */ }
      }
    }
    await Promise.allSettled([...inFlight.values()]);
  }

  return { stop };
}
