// A Java truststore holding the Huddle MITM CA, generated here in the gateway (#44).
//
// Devcontainers have no `keytool` (there is no JDK in the base images; IntelliJ
// downloads one into ~/.jdks), so the truststore cannot be created inside the
// container. And a JDK-downloaded JVM does not read the system CA store, so it
// needs a truststore pointed to by JAVA_TOOL_OPTIONS.
//
// We write the classic JKS format: every JDK reads it, and unlike a keytool-made
// PKCS12 its trusted certificates are readable without a password. Format:
// magic FEEDFEED, version 2, entry count, then per trusted-cert entry: tag 2,
// alias, timestamp, cert type "X.509", DER bytes; closed by a SHA-1 over
// (password as UTF-16BE + "Mighty Aphrodite" + everything before the digest).
import crypto from 'crypto';

export const JAVA_TRUSTSTORE_PATH = '/usr/local/share/ca-certificates/huddle-ca.jks';
export const JAVA_TRUSTSTORE_PASSWORD = 'changeit';

/** JVM flags that make every Java tool trust Huddle and go through its proxy. */
export const JAVA_TOOL_OPTIONS = [
  `-Djavax.net.ssl.trustStore=${JAVA_TRUSTSTORE_PATH}`,
  '-Djavax.net.ssl.trustStoreType=JKS',
  `-Djavax.net.ssl.trustStorePassword=${JAVA_TRUSTSTORE_PASSWORD}`,
  '-Dhttp.proxyHost=huddle',
  '-Dhttp.proxyPort=80',
  '-Dhttps.proxyHost=huddle',
  '-Dhttps.proxyPort=80',
  '-Dhttp.nonProxyHosts=localhost|127.*|[::1]',
].join(' ');

function utf(s: string): Buffer {
  const b = Buffer.from(s, 'utf8');
  const len = Buffer.alloc(2);
  len.writeUInt16BE(b.length);
  return Buffer.concat([len, b]);
}

function u32(n: number): Buffer {
  const b = Buffer.alloc(4);
  b.writeUInt32BE(n);
  return b;
}

/** DER bytes of every certificate in a PEM string. */
export function pemToDer(pem: string): Buffer[] {
  const out: Buffer[] = [];
  const re = /-----BEGIN CERTIFICATE-----([\s\S]*?)-----END CERTIFICATE-----/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(pem))) out.push(Buffer.from(m[1].replace(/\s+/g, ''), 'base64'));
  return out;
}

export function buildJksTruststore(caPem: string, password = JAVA_TRUSTSTORE_PASSWORD, now = Date.now()): Buffer {
  const certs = pemToDer(caPem);
  if (certs.length === 0) throw new Error('No certificate in the Huddle CA PEM');
  const parts: Buffer[] = [u32(0xfeedfeed), u32(2), u32(certs.length)];
  certs.forEach((der, i) => {
    const ts = Buffer.alloc(8);
    ts.writeBigUInt64BE(BigInt(now));
    parts.push(u32(2), utf(i === 0 ? 'huddle-ca' : `huddle-ca-${i}`), ts, utf('X.509'), u32(der.length), der);
  });
  const body = Buffer.concat(parts);
  const digest = crypto
    .createHash('sha1')
    .update(Buffer.from(password, 'utf16le').swap16())
    .update(Buffer.from('Mighty Aphrodite', 'utf8'))
    .update(body)
    .digest();
  return Buffer.concat([body, digest]);
}

/** Shell snippet (runs as root in the container) that writes the truststore. */
export function buildJavaTruststoreScript(caPem: string): string {
  const b64 = buildJksTruststore(caPem).toString('base64');
  return `
# Java truststore with the Huddle CA (generated by the gateway; no keytool needed, #44).
mkdir -p /usr/local/share/ca-certificates
echo '${b64}' | base64 -d > ${JAVA_TRUSTSTORE_PATH}
chmod 644 ${JAVA_TRUSTSTORE_PATH}
`;
}
